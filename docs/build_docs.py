import inspect, pydoc, sys, pathlib

try:
  import tdmslite as target_module
except ImportError:
  print("tdmslite not on current path")
  sys.exit(1)

def _indent(x:str) -> str:
  return "\n".join([f"> {a}" if not a.startswith(">") else a for a in x.split('\n')])

def generate_markdown(module, output_path:pathlib.Path|str="api"):
  output_path = pathlib.Path(output_path).resolve().with_suffix('.md')
  with open(output_path, "w", encoding="utf-8") as f:
    # Title
    f.write(f"## {module.__name__} API Reference\n"
            f"_Generated by `{pathlib.Path(__file__).name}`_\n\n")
    
    # Module Docstring
    mod_doc = inspect.getdoc(module)
    if mod_doc:
        f.write(f"{mod_doc}\n\n")
        
    # Iterate over members
    for name, obj in inspect.getmembers(module):
      # Skip private/dunder attributes unless desired
      if name.startswith("_"):
        continue
      
      if inspect.isclass(obj):
        f.write(f"---\n### `class {name}`\n\n")
        class_doc = inspect.getdoc(obj)
        if class_doc:
          f.write(f"{_indent(class_doc)}\n\n")
        
        # Extract methods
        for meth_name, meth_obj in inspect.getmembers(obj, predicate=inspect.isfunction):
          if meth_name.startswith("_") and meth_name != "__init__": continue
          sig = str(inspect.signature(meth_obj)).replace("'", "")
          f.write(f"#### {obj.__name__}.{meth_name}\n"
                  f"```python\n{obj.__name__}.{meth_name}{sig}\n```\n")
          meth_doc = inspect.getdoc(meth_obj)
          if meth_doc:
            f.write(f"{meth_doc}\n\n")
          else:
            f.write("no docs available\n\n")
                  
      elif inspect.isfunction(obj):
        sig = str(inspect.signature(obj)).replace("'", "")
        f.write(f"#### {name}\n```python\n{name}{sig}\n```\n")
        func_doc = inspect.getdoc(obj)
        if func_doc:
          f.write(f"{func_doc}\n\n")
        else:
          f.write("no docs available\n\n")

  print(f"Generated {output_path}")

if __name__ == "__main__":
    generate_markdown(target_module)
